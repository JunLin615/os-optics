"""Message catalog of the drawing sheets: every customer-visible text of the Detailed Assembly Drawing, in English and
Simplified Chinese.

``Catalog`` holds one template per (locale, key); ``text(locale, key, **values)`` fills a template with
``str.format`` named fields. Both locales have exactly the same keys and the same named fields.
The templates are generator literals: the build-time output allow-list reads them from this module's source, so a
token inside a Chinese template is a template token like any English one.

Enum values of the packages are never printed raw: each has its own key (``mechanism.LINEAR_STAGE``,
``note_code.DOF_FIXED`` ...), with a readable fallback for a value this generator does not know yet.

A key may have a ``<key>_table`` variant: the wording for a drawing on the customer's own optical table (no OpenSci
breadboard), which ``steps.Words`` picks for such a drawing; and a ``<key>_local`` variant: the wording for the drawing of
a package generated on the user's device from a local assembly plan (drawing schema 4.2: "Assembly drawing of your
design", design BOM lines), which ``steps.Words`` picks first for such a drawing.

Every Simplified Chinese text is tidied as it is filled (``tidy_zh``): no space between two Chinese characters or next
to full-width punctuation (a filled-in value may bring one), and one space between Latin letters or digits and Chinese
characters -- the house style ("将 B04 立于您的光学平台上", "SRC 放在").
"""

from __future__ import annotations

import re
from collections.abc import Mapping

LOCALES = ("en", "zh-CN")
DEFAULT_LOCALE = "en"


_CJK = "\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff"
_FULL_WIDTH = "\u3000-\u303f\uff00-\uffef\u201c\u201d\u2018\u2019"
_SPACE_BETWEEN_WIDE = re.compile(f"(?<=[{_CJK}{_FULL_WIDTH}]) +(?=[{_CJK}{_FULL_WIDTH}])")
_SPACE_AFTER_PUNCT = re.compile(f"(?<=[{_FULL_WIDTH}]) +")
_SPACE_BEFORE_PUNCT = re.compile(f" +(?=[{_FULL_WIDTH}])")
_LATIN_THEN_CJK = re.compile(f"(?<=[A-Za-z0-9])(?=[{_CJK}])")
_CJK_THEN_LATIN = re.compile(f"(?<=[{_CJK}])(?=[A-Za-z0-9])")


def tidy_zh(text: str) -> str:
    """Simplified Chinese spacing: no space around full-width punctuation or between Chinese characters; one space
    between Latin letters / digits and Chinese characters."""

    text = _SPACE_BETWEEN_WIDE.sub("", text)
    text = _SPACE_AFTER_PUNCT.sub("", text)
    text = _SPACE_BEFORE_PUNCT.sub("", text)
    text = _LATIN_THEN_CJK.sub(" ", text)
    return _CJK_THEN_LATIN.sub(" ", text)


class Catalog:
    """Templates per locale; ``text`` fills one (Simplified Chinese tidied by ``tidy_zh``)."""

    def __init__(self, messages: Mapping[str, Mapping[str, str]]) -> None:
        self.messages = messages

    def has(self, key: str) -> bool:
        return key in self.messages[DEFAULT_LOCALE]

    def text(self, locale: str, key: str, **values: object) -> str:
        filled = self.messages[locale][key].format(**values)
        return tidy_zh(filled) if locale == "zh-CN" else filled

    def enum(self, locale: str, prefix: str, value: str) -> str:
        """The text of an enum value (``prefix.VALUE``), or the value in readable words when the catalog lacks it."""

        key = f"{prefix}.{value}"
        return self.text(locale, key) if self.has(key) else value.replace("_", " ").lower()


_FIELD = re.compile(r"\{([a-z_]+)\}")


def named_fields(template: str) -> set[str]:
    """The named fields of a template."""

    return set(_FIELD.findall(template))


