"""Assembly Detail Package and local Detailed Assembly Drawing outputs.

* ``detail`` -- ``AssemblyDetailPackageV1``: the dimensioning supplement of exactly one verified Assembly Preview
  Package. It adds only what the preview cannot supply deterministically -- assembly dimension references between
  scene points with their basis -- plus binding, release and usage terms. It repeats no pose, identity, mate,
  setting, fixation, breadboard or geometry of the preview;
* ``verify`` -- canonical bytes, ``build_assembly_detail`` (binding copied from the preview manifest) and
  ``verify_assembly_detail`` / ``load_assembly_detail`` against the verified preview package, with every dimension
  measured from the preview's own poses;
* ``drawing`` -- ``AssemblyDrawingResultV1`` and ``AssemblyDrawingManifestV1``: what a local runtime's generated
  drawing shows, and the local output manifest (SVG, PDF, result) that an artifact upload carries.

Detail 3.2 and drawing 4.2 are the supplement and the drawing of a preview package with the LOCAL_PLAN binding
(generated on the user's device from a local assembly plan): they bind the local plan revision instead of a commercial
resolution and its Customer Purchase BOM, and the drawing's parts legend is the plan's design BOM.
"""

